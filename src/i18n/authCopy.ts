type Widen<T> = {
  [K in keyof T]: T[K] extends readonly (infer U)[]
    ? readonly WidenScalar<U>[]
    : WidenScalar<T[K]>;
};
type WidenScalar<T> = T extends string ? string : T;

export type AuthCopy = Widen<typeof nl>;

export function authCopy(locale: Locale): AuthCopy {
  return (locale === "en" ? en : nl) as AuthCopy;
}
